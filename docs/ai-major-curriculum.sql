CREATE TABLE ai_major_curriculum (
  course_id VARCHAR(32) PRIMARY KEY,
  course_name VARCHAR(120) NOT NULL,
  module_id INT NOT NULL,
  module_name VARCHAR(60) NOT NULL,
  course_attribute VARCHAR(10) NOT NULL CHECK (course_attribute IN ('必修', '选修')),
  standard_credit DECIMAL(4,1) NOT NULL,
  suggested_semester VARCHAR(20) NOT NULL,
  is_core BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE student_course_scores (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(64) NOT NULL,
  course_id VARCHAR(32) NOT NULL REFERENCES ai_major_curriculum(course_id),
  regular_score DECIMAL(5,2),
  final_score DECIMAL(5,2),
  total_score DECIMAL(5,2),
  study_status VARCHAR(20) NOT NULL CHECK (study_status IN ('completed', 'inProgress', 'notStarted')),
  exam_status VARCHAR(20) CHECK (exam_status IN ('通过', '不及格', '缺考', '缓考')),
  remediation_status VARCHAR(20),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (student_id, course_id)
);

CREATE INDEX idx_ai_major_curriculum_module ON ai_major_curriculum(module_id, course_attribute);
CREATE INDEX idx_student_course_scores_student ON student_course_scores(student_id);

